def table(*columns: tuple[str, str], title: str | None = None) -> Table:
    """Minimal, borderless table: header rule only, generous padding."""
    t = Table(box=box.SIMPLE_HEAD, show_edge=False, pad_edge=False, header_style="label",
              border_style="faint", padding=(0, 1), title=title, title_justify="left")
    for name, justify in columns:
        t.add_column(name, justify=justify)  # type: ignore[arg-type]
    return t


def indent(renderable, n: int = 2):
    from rich.padding import Padding

    return Padding(renderable, (0, 0, 0, n))


def banner(snap: MarketSnapshot | None = None, subtitle: str | None = None) -> None:
    console.print()
    console.print(header(subtitle) if subtitle else header())
    if snap is None:
        return
    s = snap.settings

    def line(items: list[tuple[str, str]]) -> Text:
        out = Text("  ")
        for i, (k, v) in enumerate(items):
            if i:
                out.append("  ·  ", style="faint")
            out.append(k + " ", style="muted")
            out.append(v, style="white")
        return out

    console.print(line([("Universe", " ".join(snap.tickers)),
                        ("Source", snap.price_data.source)]))
    console.print(line([
        ("History", f"{snap.start:%Y-%m-%d} → {snap.end:%Y-%m-%d} ({snap.years:.1f}y)"),
        ("Freq", s.frequency.value),
        ("r_f", pct(s.risk_free_rate)),
        ("δ", f"{s.risk_aversion:g}"),
        ("τ", f"{s.tau:g}"),
    ]))
    if snap.synthetic:
        console.print(Text("  ⚠ SYNTHETIC DATA — generated by a seeded random process, not "
                           "real market prices.", style="bold #e3b341"))


def data_notes(snap: MarketSnapshot, verbose: bool) -> None:
    notes = snap.price_data.notes
    if not notes:
        return
    shown = notes if verbose else [n for n in notes if "cache" not in n.lower()][:3]
    for n in shown:
        note(n, style="faint")


# ------------------------------------------------------------------ matrices
def matrix(values: np.ndarray, labels: Sequence[str], kind: str, fmt: str = ".2f") -> Table:
    t = Table(box=None, show_header=True, header_style="label", padding=(0, 0),
              pad_edge=False, collapse_padding=True)
    t.add_column("", justify="left", style="label", no_wrap=True)
    for lab in labels:
        t.add_column(lab, justify="right", no_wrap=True)
    lo, hi = float(values.min()), float(values.max())
    for i, lab in enumerate(labels):
        cells: list[Text | str] = [lab + "  "]
        for j in range(len(labels)):
            v = float(values[i, j])
            txt = format(v, fmt)
            cells.append(diverging_cell(v, txt) if kind == "corr"
                         else sequential_cell(v, lo, hi, txt))
        t.add_row(*cells)
    return t


def plain_matrix(values: np.ndarray, rows: Sequence[str], cols: Sequence[str], fmt: str
                 ) -> Table:
    t = table(("", "left"), *[(c, "right") for c in cols])
    for i, r in enumerate(rows):
        t.add_row(r, *[format(float(v), fmt) for v in values[i]])
    return t


# ------------------------------------------------------------------ views
def view_label(v: View) -> Text:
    t = Text()
    if v.type.value == "absolute":
        t.append(str(v.asset), style="bold white")
    else:
        t.append(str(v.long), style="bold white")
        t.append(" ≻ ", style="accent")
        t.append(str(v.short), style="bold white")
    return t


def views_table(views: Sequence[View], omega: np.ndarray | None = None,
                methods: Sequence[OmegaMethod] | None = None, rf: float | None = None,
                prior_q: np.ndarray | None = None) -> Table:
    cols = [("#", "right"), ("View", "left"), ("Stated", "right"), ("Q (excess)", "right")]
    if prior_q is not None:
        cols += [("Equil. PΠ", "right"), ("Tilt", "right")]
    cols += [("Confidence", "right")]
    if omega is not None:
        cols += [("ω", "right"), ("Ω", "left")]
    t = table(*cols)
    t.columns[1].no_wrap = True
    for k, v in enumerate(views):
        stated = pct(v.value, 2, sign=v.type.value == "relative")
        if v.type.value == "absolute":
            q = pct(v.value - rf) if rf is not None else "r − r_f"
        else:
            q = pct(v.value, 2, sign=True)
        conf = pct(v.confidence, 0) if v.confidence is not None else (
            "explicit ω" if v.omega is not None else "—")
        row: list[Text | str] = [str(k + 1), view_label(v), stated, q]
        if prior_q is not None and rf is not None:
            q_val = v.value - rf if v.type.value == "absolute" else v.value
            row += [pct(prior_q[k]), signed((q_val - prior_q[k]) * 100, 1, " pp")]
        row.append(conf)
        if omega is not None and methods is not None:
            row += [f"{omega[k, k]:.6f}", Text(methods[k].value, style="muted")]
        t.add_row(*row)
    return t


# ------------------------------------------------------------------ the portfolio screen
def portfolio_screen(report: PortfolioReport, verbose: bool) -> None:
    snap, bl, opt = report.snapshot, report.bl, report.optimized
    rf = report.rf
    tickers = snap.tickers
    w_mkt = bl.market_weights.aligned_to(tickers)
    w_bl = opt.weights.aligned_to(tickers)
    pi = bl.posterior.prior.aligned_to(tickers)
    mu = bl.posterior.posterior.aligned_to(tickers)
    vols = snap.cov.volatilities

    banner(snap)
    data_notes(snap, verbose)

    section("MARKET EQUILIBRIUM → POSTERIOR", tag("model"))
    note("Π = δΣw_mkt (implied excess returns) · μ_BL = posterior excess returns · "
         "weights optimised on (μ_BL, Σ + M)", style="faint")
    t = table(("Ticker", "left"), ("σ", "right"), ("Market w", "right"), ("Π", "right"),
              ("μ_BL", "right"), ("BL w", "right"), ("Δ w (pp)", "right"), ("", "left"))
    max_w = float(max(np.abs(w_bl).max(), np.abs(w_mkt).max()))
    for i, tk in enumerate(tickers):
        t.add_row(
            Text(tk, style="bold white"), Text(pct(vols[i], 1), style="hist"),
            pct(w_mkt[i], 1), pct(pi[i]), Text(pct(mu[i]), style="bold"),
            Text(pct(w_bl[i], 1), style="bold white"), signed((w_bl[i] - w_mkt[i]) * 100, 1),
            bar(w_bl[i], max_w, 14),
        )
    console.print(indent(t))

    section("INVESTOR VIEWS", f"{len(bl.views)} active" if bl.views else "none")
    for v in bl.inactive_views:
        note(f"Inactive: '{v.describe()}' — {', '.join(a for a in v.assets if a not in tickers)} "
             "not in this universe.", style="warn")
    if bl.views:
        post = bl.posterior
        console.print(indent(views_table(bl.views, post.omega, bl.omega_methods, rf,
                                         post.P @ post.prior.values)))
        note("Tilt = view minus what equilibrium already implies. A view below equilibrium "
             "(▼) moves weight away from its long leg even if the view itself is positive.",
             style="faint")
    else:
        note("No views. Posterior = equilibrium; the optimal portfolio is the market portfolio.")
        note("Add one:  equilibrium views add --long NVDA --short MSFT --spread 5% "
             "--confidence 70%", style="faint")

    section("PORTFOLIO", Text(f"{opt.objective.value} · {opt.constraints.describe()}",
                              style="muted"))
    stats = table(("", "left"), ("Black-Litterman", "right"), ("Market", "right"))
    er_bl = (opt.expected_excess_return or 0.0) + rf
    er_m = report.market_expected_excess + rf
    stats.add_row("Expected return (total)", Text(pct(er_bl), style="bold white"), pct(er_m))
    stats.add_row("Expected excess return", pct(opt.expected_excess_return),
                  pct(report.market_expected_excess))
    stats.add_row("Volatility (predictive)", pct(opt.volatility), pct(report.market_volatility))
    sh_m = report.market_expected_excess / report.market_volatility
    stats.add_row("Sharpe (ex-ante)", Text(num(opt.sharpe), style="bold white"), num(sh_m))
    console.print(indent(stats))
    note("All portfolio figures are model estimates under the Black-Litterman posterior, "
         "not forecasts of realised performance.", style="faint")

    if verbose:
        verbose_bl(snap, bl, report)
    assumptions(bl.assumptions)


def verbose_bl(snap: MarketSnapshot, bl: BLRun, report: PortfolioReport | None = None) -> None:
    post = bl.posterior
    tickers = snap.tickers
    section("DIAGNOSTICS", tag("model"))
    d = table(("Quantity", "left"), ("Value", "right"))
    cd = snap.cov.diagnostics
    d.add_row("Observations", f"{int(cd['observations'])}")
    d.add_row("Σ estimator", snap.cov.estimator)
    if "shrinkage_intensity" in cd:
        d.add_row("Ledoit-Wolf shrinkage", num(float(cd["shrinkage_intensity"]), 3))
    d.add_row("cond(Σ)", f"{float(cd['condition_number']):.3g}")
    d.add_row("min eigenvalue of Σ", f"{float(cd['min_eigenvalue']):.3e}")
    d.add_row("Σ repaired (PSD)", str(cd["repaired"]))
    gap = post.diagnostics.get("canonical_vs_update_max_abs_diff")
    d.add_row("|μ_canonical − μ_update|∞", f"{gap:.2e}" if isinstance(gap, float) else str(gap))
    if "cond_view_system" in post.diagnostics:
        d.add_row("cond(PτΣPᵀ + Ω)", f"{float(post.diagnostics['cond_view_system']):.3g}")
    d.add_row("Σ w_mkt", num(bl.market_weights.total, 6))
    if report:
        d.add_row("Σ w_BL", num(report.optimized.weights.total, 6))
    console.print(indent(d))

    if post.n_views:
        section("VIEW MATRICES", "P · Q · Ω")
        console.print(indent(plain_matrix(post.P, [f"view {k + 1}" for k in range(post.n_views)],
                                          tickers, "+.0f")))
        q = table(("", "left"), ("Q (excess)", "right"), ("PΠ (prior)", "right"),
                  ("Ω_kk", "right"), ("pτΣpᵀ", "right"), ("implied conf.", "right"))
        prior_pv = post.P @ post.prior.values
        for k in range(post.n_views):
            pv = float(bl.prior_view_variance[k])
            om = float(post.omega[k, k])
            q.add_row(f"view {k + 1}", pct(post.Q[k]), pct(prior_pv[k]), f"{om:.6f}",
                      f"{pv:.6f}", pct(pv / (pv + om), 0))
        console.print(indent(q))
        section("UNCERTAINTY", "√diag(M): std. error of μ_BL  vs  √diag(Σ+M): predictive σ")
        u = table(("Ticker", "left"), ("√M_ii", "right"), ("σ (Σ)", "right"),
                  ("σ (Σ+M)", "right"))
        for i, tk in enumerate(tickers):
            u.add_row(tk, pct(float(np.sqrt(post.mean_uncertainty[i, i]))),
                      pct(float(np.sqrt(snap.cov.values[i, i]))),
                      pct(float(np.sqrt(post.predictive_cov.values[i, i]))))
        console.print(indent(u))


def assumptions(items: Sequence[str]) -> None:
    section("ASSUMPTIONS")
    for a in items:
        note(a)
    console.print()


def weights_table(names: Sequence[str], columns: dict[str, np.ndarray]) -> Table:
    t = table(("Ticker", "left"), *[(c, "right") for c in columns], ("", "left"))
    first = next(iter(columns.values()))
    mx = float(max(np.abs(v).max() for v in columns.values()))
    for i, n in enumerate(names):
        t.add_row(Text(n, style="bold white"), *[pct(v[i], 1) for v in columns.values()],
                  bar(first[i], mx, 16))
    return t


def kv(rows: Sequence[tuple[str, str | Text]]) -> Group:
    t = table(("", "left"), ("", "right"))
    t.show_header = False
    for k, v in rows:
        t.add_row(Text(k, style="muted"), v)
    return Group(indent(t))
