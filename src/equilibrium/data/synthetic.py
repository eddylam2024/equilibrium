"""Deterministic synthetic market for tests, demos and offline use.

Everything produced here is fabricated by a random-number generator with a fixed seed and is
flagged ``synthetic=True`` so every CLI screen can label it. It must never be presented as
real market data.
"""

from __future__ import annotations

import hashlib
from collections.abc import Sequence

import numpy as np
import pandas as pd

from equilibrium.data.cleaning import clean_prices
from equilibrium.data.provider import AssetMetadata, MarketDataProvider, PriceData, PriceRequest

_HISTORY_START = "1995-01-02"
_PERIOD_YEARS = {"1mo": 1 / 12, "3mo": 0.25, "6mo": 0.5, "1y": 1, "2y": 2, "3y": 3, "5y": 5,
                 "10y": 10, "15y": 15, "20y": 20, "max": 25}


def _ticker_seed(ticker: str) -> int:
    return int(hashlib.sha256(ticker.encode()).hexdigest()[:8], 16)


class SyntheticProvider(MarketDataProvider):
    """Correlated geometric Brownian motion. Parameters are derived from each ticker's hash,
    so a ticker always produces the same path regardless of the other assets requested."""

    name = "Synthetic (seeded GBM — NOT real data)"
    synthetic = True

    def __init__(self, seed: int = 42, end: str = "2025-12-31", common_factor: float = 0.55
                 ) -> None:
        self.seed = seed
        self.end = pd.Timestamp(end)
        self.beta = common_factor

    def _params(self, ticker: str) -> tuple[float, float]:
        h = _ticker_seed(ticker)
        mu = 0.04 + (h % 1000) / 1000 * 0.10  # 4%..14% annual drift
        vol = 0.15 + (h // 1000 % 1000) / 1000 * 0.30  # 15%..45% annual vol
        return mu, vol

    def get_prices(self, request: PriceRequest) -> PriceData:
        end = pd.Timestamp(request.end) if request.end else self.end
        if request.start:
            start = pd.Timestamp(request.start)
        else:
            start = end - pd.DateOffset(days=int(365.25 * _PERIOD_YEARS[request.period or "10y"]))
        # one fixed history per ticker, sliced by date, so windows are mutually consistent
        full = pd.bdate_range(_HISTORY_START, self.end)
        market = np.random.default_rng(self.seed).standard_normal(len(full))
        cols = {}
        for t in request.tickers:
            mu, vol = self._params(t)
            rng = np.random.default_rng([self.seed, _ticker_seed(t)])
            z = self.beta * market + np.sqrt(1 - self.beta**2) * rng.standard_normal(len(full))
            daily = (mu - 0.5 * vol**2) / 252 + vol / np.sqrt(252) * z
            daily[0] = 0.0
            cols[t] = 100 * np.exp(np.cumsum(daily))
        raw = pd.DataFrame(cols, index=full).loc[max(start, full[0]):end]
        prices, notes = clean_prices(raw, request.tickers)
        return PriceData(prices, source=self.name, adjusted=True, synthetic=True,
                         notes=["SYNTHETIC DATA: generated by a seeded random process.", *notes])

    def get_market_caps(self, tickers: Sequence[str]) -> dict[str, float]:
        return {t: float(50e9 + (_ticker_seed(t) % 2000) * 1e9) for t in tickers}

    def get_metadata(self, tickers: Sequence[str]) -> dict[str, AssetMetadata]:
        return {t: AssetMetadata(t, f"Synthetic {t}", "USD", "SYN", "SYNTHETIC") for t in tickers}
